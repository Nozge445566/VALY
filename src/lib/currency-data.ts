const ZERO = new Set(['BIF', 'CLP', 'DJF', 'GNF', 'ISK', 'JPY', 'KMF', 'KRW', 'PYG', 'RWF', 'UGX', 'UYI', 'VND', 'VUV', 'XAF', 'XOF', 'XPF']);
const THREE = new Set(['BHD', 'IQD', 'JOD', 'KWD', 'LYD', 'OMR', 'TND']);

/** Decimal places of a currency (ISO 4217 minor units). Unknown codes: 2. */
export function currencyDecimals(code: string): number {
  const c = code.toUpperCase();
  return ZERO.has(c) ? 0 : THREE.has(c) ? 3 : 2;
}

/** Currency of a country, or null when the country is unknown. */
export function currencyOfCountry(country: string | null | undefined): string | null {
  if (!country) return null;
  return COUNTRY_CURRENCY[country.trim().toUpperCase()] ?? null;
}

/**
 * Which currency to show: explicit choice (valid ISO-like code) -> country of the user -> null (caller decides; USD only with a visible note).
 */
/** Display currency: decided ONLY by the country of the device (product rule: no picker, no override). */
export function pickDisplayCurrency(country: string | null | undefined): { code: string | null; from: "country" | "none" } {
  const c = currencyOfCountry(country);
  return c ? { code: c, from: "country" } : { code: null, from: "none" };
}
